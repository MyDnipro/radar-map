function resolveLocationFromText(rawText) {
  if (!rawText) return null;
  const text = rawText.toLowerCase();

  // 1. Канатна / Інфекційна лікарня №21 (ЖЕЛЕЗНЫЙ ПРИОРИТЕТ над Рабочей!)
  if (text.includes("канатн") || text.includes("інфекцій") || text.includes("инфекцион") || text.includes("21 лікарн") || text.includes("21 больниц")) {
    return { lat: 48.46350, lng: 35.00980, name: "вул. Канатна (Інфекційна лікарня №21)" };
  }

  // 2. Щепкіна (ЖЕЛЕЗНЫЙ ПРИОРИТЕТ над Нигояна / Чечелевкой!)
  if (text.includes("щепкін") || text.includes("щепкин")) {
    return { lat: 48.47350, lng: 34.99680, name: "вул. Щепкіна" };
  }

  // 3. Річпорт
  if (text.includes("речпорт") || text.includes("річпорт") || text.includes("ричпор") || text.includes("речпор") || text.includes("речной вокзал") || text.includes("річковий вокзал")) {
    return { lat: 48.48094, lng: 35.02514, name: "Річпорт (Набережна Заводська)" };
  }

  // 4. Павлова біля Ауді Центру
  if (text.includes("павлова") || text.includes("павлов") || text.includes("академіка павлова") || text.includes("академика павлова")) {
    return { lat: 48.48022, lng: 35.00658, name: "вул. Академіка Павлова" };
  }

  // 5. Краснозаводська / Белелюбського / САТ Торус
  if (text.includes("краснозавод") || text.includes("белелюб") || text.includes("білелюб") || text.includes("торус") || text.includes("дтрз") || text.includes("комбайн")) {
    return { lat: 48.4800, lng: 34.9880, name: "вул. Краснозаводська (Белелюбського / САТ)" };
  }

  // 6. Водолікарня
  if (text.includes("водолечеб") || text.includes("водолікарн") || text.includes("водоликарн") || text.includes("грязелечеб")) {
    return { lat: 48.4848, lng: 34.9735, name: "Водолікарня (просп. Свободи)" };
  }

  // 7. Вечні вогні
  if (text.includes("огни") || text.includes("вогні") || text.includes("вечные огни") || text.includes("вечні вогні")) {
    return { lat: 48.4765, lng: 34.9860, name: "просп. Сергія Нігояна (Вечні вогні)" };
  }

  // 8. Мазепи / Петровського (48.47192, 34.98864)
  if (text.includes("низ мазеп") || text.includes("низ петровськ") || text.includes("низ петровск")) {
    return { lat: 48.47192, lng: 34.98864, name: "просп. Івана Мазепи (низ)" };
  }
  if (text.includes("мазеп") || text.includes("петровськ") || text.includes("петровск")) {
    return { lat: 48.47192, lng: 34.98864, name: "просп. Івана Мазепи" };
  }

  for (const [key, item] of Object.entries(DNIPRO_STREETS_MAP)) {
    if (text.includes(key)) {
      return { lat: item.lat, lng: item.lng, name: item.name };
    }
    if (item.old && text.includes(item.old.toLowerCase())) {
      return { lat: item.lat, lng: item.lng, name: item.name };
    }
  }
  return null;
}

