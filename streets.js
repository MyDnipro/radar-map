function resolveLocationFromText(rawText) {
  const clean = (rawText || "")
    .replace(/&#\d+;/g, " ")
    .replace(/&[a-z]+;/gi, " ");
  
  const lower = clean.toLowerCase();
  const isIntersection = /(?:перехрест|перетин|угол|кут|съезд|съезжать|спуск|подъем|підйом|поворот|з['’]їзд|\/|\\|\+|\bс\b.*?\bна\b|\bз\b.*?\bна\b)/i.test(lower);
  
  const sortedKeys = Object.keys(DNIPRO_STREETS_MAP).sort((a, b) => b.length - a.length);
  const matches = [];

  for (const key of sortedKeys) {
    if (new RegExp(key, "i").test(lower)) {
      const item = DNIPRO_STREETS_MAP[key];
      if (!matches.some(m => m.name === item.name)) {
        matches.push(item);
      }
    }
  }

  if (matches.length >= 2) {
    return {
      name: `${matches[0].name} / ${matches[1].name} (розв'язка)`,
      lat: Number(((matches[0].lat + matches[1].lat) / 2).toFixed(5)),
      lng: Number(((matches[0].lng + matches[1].lng) / 2).toFixed(5)),
      isIntersection: true,
      street1: matches[0].name,
      street2: matches[1].name
    };
  }

  if (matches.length > 0) {
    return {
      name: matches[0].name,
      lat: matches[0].lat,
      lng: matches[0].lng,
      isIntersection: false
    };
  }
  return null;
}

function getStreetRenameNote(text) {
  const clean = (text || "")
    .replace(/&#\d+;/g, " ")
    .replace(/&[a-z]+;/gi, " ");

  const lower = clean.toLowerCase();
  const isLandmarkOnly = /(?:ровд|восток\s*газ|млин|варус|атб|заправк|окко|вокзал|станція|міст|пост|парк|озерк|бик)/i.test(lower);

  const sortedKeys = Object.keys(DNIPRO_STREETS_MAP).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (new RegExp(key, "i").test(lower)) {
      const val = DNIPRO_STREETS_MAP[key];
      if (val.old) return `💡 ${val.old} ➔ по-новому: <b>${val.name}</b>`;
      else return `💡 <b>${val.name}</b> (назва не змінювалась)`;
    }
  }

  if (isLandmarkOnly) {
    return `💡 Локальний міський орієнтир`;
  }
  return `💡 Міський орієнтир`;
}
