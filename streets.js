function resolveLocationFromText(rawText) {
  if (!rawText) return null;
  const text = rawText.toLowerCase();

  // Приоритетная фиксация Речпорта
  if (text.includes("речпорт") || text.includes("річпорт")) {
    return { lat: 48.4805, lng: 35.0210, name: "Річпорт (Набережна Заводська)" };
  }

  for (const [key, item] of Object.entries(DNIPRO_STREETS_MAP)) {
    if (text.includes(key)) {
      return { lat: item.lat, lng: item.lng, name: item.name };
    }
    if (item.old && text.includes(item.old.toLowerCase())) {
      return { lat: item.lat, lng: item.lng, name: item.name };
    }
  }
  return null;
}

function getStreetRenameNote(rawText) {
  if (!rawText) return "";
  const text = rawText.toLowerCase();

  for (const [key, item] of Object.entries(DNIPRO_STREETS_MAP)) {
    if (text.includes(key) || (item.old && text.includes(item.old.toLowerCase()))) {
      if (item.type === "landmark") {
        return "📍 Місцевий орієнтир";
      }
      if (item.type === "not_renamed") {
        return "📍 Не перейменовувалась";
      }
      if (item.type === "renamed") {
        return `📍 Нова назва: ${item.name}`;
      }
    }
  }
  return "📍 Не перейменовувалась";
}

