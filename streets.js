function resolveLocationFromText(rawText) {
  if (!rawText) return null;
  const text = rawText.toLowerCase();

  for (const [key, item] of Object.entries(DNIPRO_STREETS_MAP)) {
    if (text.includes(key)) {
      return { lat: item.lat, lng: item.lng, name: item.name };
    }
    if (item.old && text.includes(item.old.toLowerCase())) {
      return { lat: item.lat, lng: item.lng, name: item.name };
    }
  }
  return null;
}

function getStreetRenameNote(rawText) {
  if (!rawText) return "";
  const text = rawText.toLowerCase();

  for (const [key, item] of Object.entries(DNIPRO_STREETS_MAP)) {
    if (item.old && text.includes(item.old.toLowerCase())) {
      return `ℹ️ <b>${item.old}</b> перейменовано на <b>${item.name}</b>`;
    }
  }
  return "";
}

